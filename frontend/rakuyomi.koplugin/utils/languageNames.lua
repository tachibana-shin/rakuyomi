--- Normalises a raw language code coming from a source repo:
--- 1. Lowercases.
--- 2. Strips BCP-47 regional/script subtags (`zh-Hans` -> `zh`,
---    `pt-BR` -> `pt`, `es-419` -> `es`).
--- 3. Canonicalises special multi-language values (`all`, `other`,
---    `multisrc`) to the single key `multi`.
--- @param code string
--- @return string normalised key suitable for `nameFor()`
local function normalize(code)
  local c = code:lower()
  -- Strip BCP-47 subtags (everything after the first `-`)
  c = c:match("^([^%-]+)") or c
  -- Canonicalise special multi-language values
  if c == "multisrc" or c == "all" or c == "other" then
    return "multi"
  end
  return c
end

--- Returns the human-readable English name for a language code, or the
--- original code verbatim if no mapping exists.
--- @param code string  ISO 639-1 code (may include BCP-47 subtag)
--- @return string
local function nameFor(code)
  local key = normalize(code)
  return LANG_NAME[key] or code
end

return {
  normalize = normalize,
  nameFor = nameFor,
}
